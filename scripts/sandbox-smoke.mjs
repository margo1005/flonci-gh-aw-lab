import {mkdtempSync,writeFileSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {tmpdir} from 'node:os';
import {spawnSync} from 'node:child_process';
import {image} from './policy.mjs';
const dir=mkdtempSync(resolve(tmpdir(),'heb-smoke-'));
const file=resolve(dir,'budget.mjs');
const runner=resolve(dirname(fileURLToPath(import.meta.url)),'evaluate.mjs');
const env={PATH:process.env.PATH};
const pull=spawnSync('docker',['pull',image],{encoding:'utf8',timeout:120000,env});
assert.equal(pull.status,0,'Pinned image unavailable');
const args=['run','--rm','--network','none','--read-only','--cap-drop','ALL','--security-opt','no-new-privileges','--pids-limit','32','--memory','128m','--cpus','1','--user','65534:65534','--mount','type=bind,src='+file+',dst=/implementation/budget.mjs,readonly','--mount','type=bind,src='+runner+',dst=/runner/evaluate.mjs,readonly',image,'node','--experimental-vm-modules','/runner/evaluate.mjs','a','b'];
writeFileSync(file,'export function validateBudget(min,max){return {min,max};}\n');
let r=spawnSync('docker',args,{encoding:'utf8',timeout:15000,env});
assert.equal(r.status,0);assert.deepEqual(JSON.parse(r.stdout),{min:'a',max:'b'});
writeFileSync(file,"import assert from 'node:assert/strict'; export function validateBudget(){return null;}\n");
r=spawnSync('docker',args,{encoding:'utf8',timeout:15000,env});
assert.notEqual(r.status,0,'Candidate imports must be denied');
console.log('Sandbox protocol positive control passed; forbidden import rejected.');
